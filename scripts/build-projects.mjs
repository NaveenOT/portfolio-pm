import {readdir, readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=new URL('../content/projects/',import.meta.url);
const files=(await readdir(root)).filter(x=>x.endsWith('.json')).sort();
const projects=[],ids=new Set();
for(const file of files){
 const p=JSON.parse(await readFile(new URL(file,root),'utf8'));
 for(const key of ['id','title','description','status','type'])if(typeof p[key]!=='string'||!p[key].trim())throw Error(`${file}: ${key} must be nonempty text`);
 if(!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(p.id)||ids.has(p.id))throw Error(`${file}: invalid or duplicate id`);
 if(!Array.isArray(p.sections)||!p.sections.length||p.sections.some(s=>!Array.isArray(s)||s.length!==2||s.some(v=>typeof v!=='string'||!v.trim())))throw Error(`${file}: sections must be [heading, text] pairs`);
 if(!Array.isArray(p.stack)||p.stack.some(s=>typeof s!=='string'))throw Error(`${file}: stack must be a string array`);
 if(p.url&&!/^https:\/\//.test(p.url))throw Error(`${file}: url must be HTTPS`);
 if(p.order!==undefined&&!Number.isFinite(p.order))throw Error(`${file}: order must be a number`);
 ids.add(p.id);projects.push(p);
}
projects.sort((a,b)=>(a.order??100)-(b.order??100)||a.id.localeCompare(b.id));
await writeFile(new URL('../dist/projects.generated.js',import.meta.url),'// Generated by scripts/build-projects.mjs. Edit content/projects/*.json.\nexport const projects='+JSON.stringify(projects,null,2)+';\n');
console.log(`Built ${projects.length} projects from ${fileURLToPath(root)}`);
